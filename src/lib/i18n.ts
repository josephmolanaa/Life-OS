

export type Lang = 'en' | 'id';


export async function getLang(): Promise<Lang> {
  if (typeof window !== 'undefined') {
    // Client-side fallback reading from document.cookie
    const match = document.cookie.match(/(^| )finance-lang=([^;]+)/);
    return match && match[2] === 'id' ? 'id' : 'en';
  }
  
  // Server-side
  try {
    const { cookies } = await import('next/headers');
    const cookieStore = await cookies();
    return cookieStore.get('finance-lang')?.value === 'id' ? 'id' : 'en';
  } catch (e) {
    return 'en';
  }
}


